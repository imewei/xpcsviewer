def test_zero_swing_matches_five_argument_call() -> None:
    five, _ = compute_transmission_qmap(*ARGS)
    compute_transmission_qmap.cache_clear()
    seven, _ = compute_transmission_qmap(*ARGS, 0.0, 0.0)
    for key in KEYS:
        assert np.array_equal(five[key], seven[key]), key


