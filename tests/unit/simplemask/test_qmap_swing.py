def _rotated_alpha_phi(h_deg: float, v_deg: float) -> tuple[np.ndarray, np.ndarray]:
    """Rotate the detector vectors with NumPy, independent of the module."""
    rows = (np.arange(SHAPE[0]) - CENTER[0]) * PIX_DIM
    cols = (np.arange(SHAPE[1]) - CENTER[1]) * PIX_DIM
    vg, hg = np.meshgrid(rows, cols, indexing="ij")
    vec = np.stack([hg, vg, np.full_like(vg, DET_DIST)], axis=-1)
    a, b = np.deg2rad(h_deg), np.deg2rad(v_deg)
    rx = np.array([[1, 0, 0], [0, np.cos(b), -np.sin(b)], [0, np.sin(b), np.cos(b)]])
    ry = np.array([[np.cos(a), 0, -np.sin(a)], [0, 1, 0], [np.sin(a), 0, np.cos(a)]])
    rot = vec @ (ry @ rx).T
    alpha = np.arccos(rot[..., 2] / np.linalg.norm(rot, axis=-1))
    phi = -np.arctan2(rot[..., 1], rot[..., 0])
    return alpha, phi


def test_swung_components_match_rotated_vectors() -> None:
    qmap, _ = compute_transmission_qmap(*ARGS, 20.0, 15.0)
    alpha, phi = _rotated_alpha_phi(20.0, 15.0)
    k0 = _k0(ENERGY)
    np.testing.assert_allclose(qmap["TTH"], np.rad2deg(alpha), rtol=1e-10)
    np.testing.assert_allclose(qmap["phi"], np.rad2deg(phi), rtol=1e-10)
    np.testing.assert_allclose(qmap["qx"], k0 * np.sin(alpha) * np.cos(phi), rtol=1e-10)
    np.testing.assert_allclose(qmap["qy"], k0 * np.sin(alpha) * np.sin(phi), rtol=1e-10)
    np.testing.assert_allclose(qmap["q"], 2 * k0 * np.sin(alpha / 2), rtol=1e-10)


@pytest.mark.parametrize("swing", [(20.0, 0.0), (0.0, 15.0), (20.0, 15.0)])
def test_swung_matches_upstream(swing: tuple[float, float]) -> None:
    qmap, _ = compute_transmission_qmap(*ARGS, *swing)
    golden = UPSTREAM_SWUNG[swing]
    for key in ("TTH", "phi", "q"):
        np.testing.assert_allclose(
            qmap[key], golden[key], rtol=1e-12, atol=1e-12, err_msg=key
        )
    # Upstream stores qx/qy as float32; this repository keeps float64.
    for key in ("qx", "qy"):
        np.testing.assert_allclose(
            qmap[key], golden[key], rtol=1e-6, atol=1e-12, err_msg=key
        )
        assert qmap[key].dtype == np.float64


def test_q_is_momentum_transfer_magnitude() -> None:
    qmap, _ = compute_transmission_qmap(ENERGY, CENTER, SHAPE, PIX_DIM, 1.0)
    tth = np.deg2rad(qmap["TTH"])
    assert tth.max() > 0.2  # wide angle: the old k0*sin(alpha) is off by ~0.5%
    np.testing.assert_allclose(
        qmap["q"], 2 * _k0(ENERGY) * np.sin(tth / 2), rtol=1e-12, atol=1e-12
    )


